"""质疑检测的关键词正则模式。

说明：这里不再维护「主动学习触发词表」。学习提示的注入条件是
「本地记忆无命中」（见 main.py 的 _get_learn_prompt 调用处），
与用户的问法无关；早期版本遗留的 ACTIVE_LEARN_PATTERNS 从未被引用，
保留它会让人误以为提问句式需要命中词表才会触发检索，故已移除。
"""

import re

# 质疑检测模式：用户对当前记忆结果提出疑问
CHALLENGE_PATTERNS = [
    r"(?:这|这个|这个信息|这条|这个说法|你说的)(?:不对|错了吧|有问题|不准确|过时|假的|瞎说|编的)",
    r"(?:你确定|真的吗|靠谱吗|可信吗|是不是搞错了|确定没错)",
    r"(?:质疑|怀疑|反驳|纠正|勘误)",
    r"(?:不对吧|错了吧|假的吧|编的吧|记错了吧)",
    r"(?:不是这样的|事实并非如此|实际上)",
    r"(?:最新|更新|变了).+(?:吗|没|没有)",
]

# 记忆召回需求判定模式（按需触发）：只有命中这些指代/命令才做全库 FTS/向量。
# 日常寒暄（"晚上好"、"你现在怎么样"）不应付检索成本，故默认跳过。
# 判定保守：宁可不召回，也不让普通聊天付全库检索；可用 memory_recall_gate_enabled 关闭。
MEMORY_RECALL_PATTERNS = [
    r"还记得",
    r"记得(?:吗|不记得|我们|之前|上次|以前|那天|曾经)",
    r"(?:回忆|想起|记起|回想)",
    r"(?:之前|上次|昨天|前天|那天|以前|曾经|当初).{0,14}(?:说|聊|提|告诉|讲|做过|约定|答应|聊过)",
    r"(?:跟我说过|告诉过我|提过|讲过|聊过|答应过)",
    r"(?:那个人|某某|我跟你说的|我之前说的)",
    r"(?:那件事|那个事情|我们说好的|我们说定了)",
    r"(?:帮我|请你?|你能|给我).{0,6}(?:查|回忆|回想).{0,4}记忆",
    r"(?:你记得吗|还记得吗|回忆一下|回想一下|查一下记忆)",
]
MEMORY_RECALL_COMPILED = tuple(re.compile(pattern) for pattern in MEMORY_RECALL_PATTERNS)
